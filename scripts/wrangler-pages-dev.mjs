#!/usr/bin/env node
// Run `wrangler pages dev` with local secrets in .dev.vars, never in argv.
//
// Why: a secret passed as `--binding KEY=value` is visible to anything that lists processes
// (`ps aux`, `pgrep -fl`). On 2026-10-07 two agent sessions printed about seven of this
// project's live credentials into persisted transcripts that way, from the acceptance-review
// harnesses' wrangler servers. Wrangler reads `.dev.vars` from the directory that holds the
// Wrangler config ("Local development with secrets", Cloudflare Workers docs), so the values
// go there and only file paths reach the command line.
//
// usage: node scripts/wrangler-pages-dev.mjs <cwd> [wrangler pages dev args...]
//   <cwd>   checkout or worktree holding wrangler.toml. .dev.vars is written there with mode
//           0600 and removed when wrangler exits. A .dev.vars this script did not write is
//           used as-is and left alone.
//   env WRANGLER_DEV_VARS_SOURCE  dotenv file to copy (default: the main checkout's .env.local,
//                                  so a linked worktree finds it too)
//   env WRANGLER_BIN              wrangler executable (default: <cwd>, then the main checkout's,
//                                  node_modules/.bin/wrangler; else npx wrangler)
import { existsSync, readFileSync, rmSync, writeFileSync, chmodSync } from 'node:fs';
import { execFileSync, spawn } from 'node:child_process';
import { dirname, join, resolve } from 'node:path';

const MARKER = '# generated by scripts/wrangler-pages-dev.mjs from .env.local; removed on exit';

const [cwdArg, ...wranglerArgs] = process.argv.slice(2);
if (!cwdArg) {
	console.error('usage: node scripts/wrangler-pages-dev.mjs <cwd> [wrangler pages dev args...]');
	process.exit(2);
}
const cwd = resolve(cwdArg);

// Refuse the leak this script exists to prevent.
const inlineSecret = wranglerArgs.findIndex(
	(a, i) => /^(--binding|-b)=.+=/.test(a) || ((a === '--binding' || a === '-b') && /=/.test(wranglerArgs[i + 1] ?? ''))
);
if (inlineSecret !== -1) {
	console.error('Refusing --binding KEY=value: values in argv are readable by any process listing. Put them in .env.local.');
	process.exit(2);
}

function mainCheckout() {
	try {
		const common = execFileSync('git', ['rev-parse', '--path-format=absolute', '--git-common-dir'], {
			cwd,
			encoding: 'utf8',
			stdio: ['ignore', 'pipe', 'ignore']
		}).trim();
		return dirname(common);
	} catch {
		return cwd;
	}
}

const main = mainCheckout();
const source = process.env.WRANGLER_DEV_VARS_SOURCE ?? join(main, '.env.local');
const devVars = join(cwd, '.dev.vars');

let owned = false;
if (existsSync(devVars) && !readFileSync(devVars, 'utf8').startsWith(MARKER)) {
	console.log(`using existing ${devVars} (not written by this script; left in place)`);
} else {
	const lines = readFileSync(source, 'utf8')
		.split('\n')
		.filter((l) => /^\s*(export\s+)?[A-Za-z_][A-Za-z0-9_]*\s*=/.test(l))
		.map((l) => l.replace(/^\s*export\s+/, ''));
	writeFileSync(devVars, [MARKER, ...lines, ''].join('\n'), { mode: 0o600 });
	chmodSync(devVars, 0o600); // mode applies only on create; an older copy of ours may exist
	owned = true;
	const names = lines.map((l) => l.split('=')[0].trim());
	console.log(`wrote ${devVars} (0600) with ${names.length} values; names only: ${names.join(',')}`);
}

function cleanup() {
	if (owned) rmSync(devVars, { force: true });
	owned = false;
}

const local = [join(cwd, 'node_modules/.bin/wrangler'), join(main, 'node_modules/.bin/wrangler')].find((p) => existsSync(p));
const bin = process.env.WRANGLER_BIN ?? local;
const [cmd, args] = bin ? [bin, ['pages', 'dev', ...wranglerArgs]] : ['npx', ['wrangler', 'pages', 'dev', ...wranglerArgs]];

const child = spawn(cmd, args, { cwd, stdio: 'inherit' });
for (const sig of /** @type {const} */ (['SIGINT', 'SIGTERM', 'SIGHUP'])) {
	process.on(sig, () => child.kill(sig));
}
child.on('error', (err) => {
	cleanup();
	console.error(err.message);
	process.exit(1);
});
child.on('exit', (code, signal) => {
	cleanup();
	process.exit(code ?? (signal ? 1 : 0));
});
